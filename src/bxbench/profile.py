"""Shared data-profiling logic used by notebooks/profile_data.ipynb.

Kept here (not inline in the notebook) so the numbers going into
reports/data_profile.md have one source of truth, even though profiling
itself happens interactively in the notebook: one-off exploration lives in
notebooks, reusable pipeline steps (split, eval, training) live in .py.
"""

import pandas as pd

BUCKET_BINS = [0, 2, 5, 20, float("inf")]
BUCKET_LABELS = ["1-2", "3-5", "6-20", "21+"]


def bucketize(counts: pd.Series) -> pd.Series:
    return pd.cut(counts, bins=BUCKET_BINS, labels=BUCKET_LABELS)


def compute_profile(
    users: pd.DataFrame,
    books: pd.DataFrame,
    ratings: pd.DataFrame,
    descriptions: pd.DataFrame,
) -> dict:
    profile: dict = {}

    profile["row_counts"] = {
        "users": len(users),
        "books": len(books),
        "ratings": len(ratings),
        "descriptions": len(descriptions),
    }

    age_valid = users["Age"].dropna()
    age_plausible = age_valid[(age_valid >= 5) & (age_valid <= 100)]
    profile["age_null_pct"] = users["Age"].isna().mean() * 100
    profile["age_implausible_pct"] = (
        ((age_valid < 5) | (age_valid > 100)).mean() * 100 if len(age_valid) else 0.0
    )
    profile["age_mean"] = age_plausible.mean() if len(age_plausible) else float("nan")
    profile["age_median"] = (
        age_plausible.median() if len(age_plausible) else float("nan")
    )

    n_total = len(ratings)
    n_implicit = int((ratings["Book-Rating"] == 0).sum())
    n_explicit = n_total - n_implicit
    profile["n_total_ratings"] = n_total
    profile["n_implicit"] = n_implicit
    profile["n_explicit"] = n_explicit
    profile["explicit_dist"] = (
        ratings.loc[ratings["Book-Rating"] > 0, "Book-Rating"]
        .value_counts()
        .sort_index()
        .rename_axis("rating")
        .reset_index(name="count")
        .astype({"rating": "int64", "count": "int64"})
        .assign(pct_of_explicit=lambda d: d["count"] / n_explicit * 100)
    )

    per_user = ratings.groupby("User-ID").size()
    profile["per_user_mean"] = per_user.mean()
    profile["per_user_median"] = per_user.median()
    profile["per_user_max"] = int(per_user.max())
    profile["n_users_rated"] = len(per_user)
    profile["n_singleton_users"] = int((per_user == 1).sum())
    profile["user_buckets"] = (
        bucketize(per_user)
        .value_counts()
        .reindex(BUCKET_LABELS)
        .rename_axis("bucket")
        .reset_index(name="n_users")
        .assign(pct=lambda d: d["n_users"] / len(per_user) * 100)
    )

    per_book = ratings.groupby("ISBN").size()
    profile["per_book_mean"] = per_book.mean()
    profile["per_book_median"] = per_book.median()
    profile["per_book_max"] = int(per_book.max())
    profile["book_buckets"] = (
        bucketize(per_book)
        .value_counts()
        .reindex(BUCKET_LABELS)
        .rename_axis("bucket")
        .reset_index(name="n_books")
        .assign(pct=lambda d: d["n_books"] / len(per_book) * 100)
    )

    desc_isbns = set(descriptions["ISBN"])
    book_isbns = set(books["ISBN"])
    all_book_counts = per_book.reindex(list(book_isbns)).fillna(0)
    cov_df = pd.DataFrame(
        {
            "bucket": bucketize(all_book_counts),
            "has_desc": [isbn in desc_isbns for isbn in all_book_counts.index],
        }
    )
    cov = (
        cov_df.groupby("bucket", observed=False)["has_desc"]
        .agg(["sum", "count"])
        .reindex(BUCKET_LABELS)
    )
    cov["coverage_pct"] = cov["sum"] / cov["count"] * 100
    profile["coverage_by_bucket"] = cov.rename_axis("bucket").reset_index()
    profile["n_desc_in_catalog"] = len(desc_isbns & book_isbns)
    profile["n_books_in_catalog"] = len(book_isbns)

    return profile


def render_markdown(profile: dict) -> str:
    lines: list[str] = ["# Data Profile — Book-Crossing\n"]
    lines.append("Generated by `notebooks/profile_data.ipynb`.\n")

    lines.append("## Row counts\n")
    for k, v in profile["row_counts"].items():
        lines.append(f"- {k}: {v:,}")
    lines.append("")

    lines.append("## Users\n")
    lines.append(f"- Age null: {profile['age_null_pct']:.1f}%")
    lines.append(
        f"- Age implausible (<5 or >100) among non-null: "
        f"{profile['age_implausible_pct']:.1f}%"
    )
    lines.append(
        f"- Age (non-null, plausible 5-100) — mean {profile['age_mean']:.1f}, "
        f"median {profile['age_median']:.1f}\n"
    )

    lines.append("## Ratings: explicit vs. implicit\n")
    n_total, n_implicit, n_explicit = (
        profile["n_total_ratings"],
        profile["n_implicit"],
        profile["n_explicit"],
    )
    lines.append(
        f"- implicit (Book-Rating == 0): {n_implicit:,} ({n_implicit/n_total*100:.1f}%)"
    )
    lines.append(
        f"- explicit (Book-Rating 1-10): {n_explicit:,} ({n_explicit/n_total*100:.1f}%)"
    )
    lines.append("\nExplicit rating value distribution:\n")
    lines.append("| rating | count | pct of explicit |")
    lines.append("|---|---|---|")
    # NOTE: iterrows() upcasts a row's dtype to a common type across mixed
    # int/float columns, so int columns come back as floats per-row even
    # though the column dtype is int64 -- cast explicitly rather than trust
    # row[...] formatting.
    for _, row in profile["explicit_dist"].iterrows():
        lines.append(
            f"| {int(row['rating'])} | {int(row['count']):,} | "
            f"{row['pct_of_explicit']:.1f}% |"
        )
    lines.append("")

    lines.append("## Interactions per user (history depth)\n")
    lines.append(
        f"- mean {profile['per_user_mean']:.2f}, median {profile['per_user_median']:.0f}, "
        f"max {profile['per_user_max']:,}"
    )
    lines.append("\n| history-depth bucket | # users | % of users |")
    lines.append("|---|---|---|")
    for _, row in profile["user_buckets"].iterrows():
        lines.append(
            f"| {row['bucket']} | {int(row['n_users']):,} | {row['pct']:.1f}% |"
        )
    n_single = profile["n_singleton_users"]
    n_rated = profile["n_users_rated"]
    lines.append(
        f"\n- users with exactly 1 interaction (unusable for leave-k-out "
        f"eval with k>=1 train + 1 test): {n_single:,} "
        f"({n_single/n_rated*100:.1f}%) — these can only ever be "
        f"pure cold-start / popularity-fallback cases, flag separately in "
        f"the eval harness rather than dropping silently.\n"
    )

    lines.append("## Interactions per book (popularity)\n")
    lines.append(
        f"- mean {profile['per_book_mean']:.2f}, median {profile['per_book_median']:.0f}, "
        f"max {profile['per_book_max']:,}"
    )
    lines.append("\n| popularity bucket | # books | % of books |")
    lines.append("|---|---|---|")
    for _, row in profile["book_buckets"].iterrows():
        lines.append(
            f"| {row['bucket']} | {int(row['n_books']):,} | {row['pct']:.1f}% |"
        )
    lines.append("")

    lines.append("## Description coverage by book popularity bucket\n")
    lines.append(
        "Does description coverage skew toward popular books (which would mean "
        "Tier 4's content signal is concentrated where CF already does fine, and "
        "least available for the cold-start tail)? Answer: no, roughly flat "
        "(~2.3-3.3%) across popularity buckets.\n"
    )
    lines.append("| popularity bucket | # with description | # books | coverage |")
    lines.append("|---|---|---|---|")
    for _, row in profile["coverage_by_bucket"].iterrows():
        lines.append(
            f"| {row['bucket']} | {int(row['sum']):,} | {int(row['count']):,} | "
            f"{row['coverage_pct']:.2f}% |"
        )
    n_desc, n_books = profile["n_desc_in_catalog"], profile["n_books_in_catalog"]
    lines.append(f"\n- overall: {n_desc:,} / {n_books:,} ({n_desc/n_books*100:.1f}%)\n")

    return "\n".join(lines)
